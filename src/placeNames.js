// Country and subdivision names, so a filter reads "United States" rather than "US".
//
// ISO codes are specialist notation. There is no reason a reader would know that NZ is New Zealand,
// and "MD" is genuinely ambiguous — Moldova as a country, Maryland as a US state — so the same two
// letters mean different things depending on which field they are in. Showing names is not a
// convenience, it is correct labelling.
//
// SUBDIVISIONS ARE ONLY MAPPED WHERE THE SOURCE ABBREVIATES THEM. PeeringDB's `state` field is
// freeform: the US, Canada, Australia and Brazil send codes, while India sends "Maharashtra" and
// others send nothing. Anything without a match passes through unchanged rather than being dropped
// or guessed at — a name we cannot expand is still a name someone wrote down.

